/**
 * Helper that returns the localized fields of a recipe, falling back to French
 * when an English translation is not available.
 */
export function localizeRecipe(recipe: Recipe, lang: "fr" | "en") {
  const isEn = lang === "en";

  return {
    name: isEn ? (recipe.name_en ?? recipe.name) : recipe.name,
    ingredients: isEn
      ? (recipe.ingredients_en ?? recipe.ingredients)
      : recipe.ingredients,
    timeToCook: isEn
      ? (recipe.timeToCook_en ?? recipe.timeToCook)
      : recipe.timeToCook,
  };
}

/**
 * Langue réelle d'un texte affiché : quand la traduction anglaise manque, le
 * texte français s'affiche dans l'interface anglaise et doit être déclaré
 * `lang="fr"` (WCAG 3.1.2). Renvoie `undefined` quand la langue du document
 * suffit, pour ne pas ajouter d'attribut inutile.
 */
export function fallbackLang(
  translated: unknown,
  lang: "fr" | "en",
): "fr" | undefined {
  return lang === "en" && translated == null ? "fr" : undefined;
}

export function localizeDescription(
  text: RecipeDescription,
  lang: "fr" | "en",
) {
  return lang === "en"
    ? (text.description_en ?? text.description)
    : text.description;
}

export function localizeChief(chief: Chief, lang: "fr" | "en") {
  return {
    name: chief.name,
    description:
      lang === "en"
        ? (chief.description_en ?? chief.description)
        : chief.description,
  };
}

export function splitCookingTime(raw: string): {
  prep: string;
  cook: string | null;
} {
  const [prepRaw = "", cookRaw] = raw.split("+").map((s) => s.trim());
  if (!cookRaw) return { prep: prepRaw, cook: null };
  const cook = cookRaw
    .replace(/\s*de\s+cuisson\s*$/i, "")
    .replace(/\s*cooking\s+time\s*$/i, "")
    .trim();
  return { prep: prepRaw, cook };
}
